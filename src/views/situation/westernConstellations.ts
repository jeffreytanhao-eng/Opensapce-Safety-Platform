/** 星空球半径（场景单位）：与中国星官层同一球面，两套图层叠合 */
export const WESTERN_CONSTELLATION_RADIUS = 150
/** 连线线宽（CSS 像素，LineMaterial 走像素口径）：比星官连线稍细，作背景参考 */
const WESTERN_LINE_WIDTH = 1.1
/** 统一配色：淡青蓝（区别于星官层的四象/三垣分色） */
export const WESTERN_COLOR = 0x9fc4ff

/** 赤经/赤纬（度）→ 场景坐标（挂场景根，惯性系） */
export function raDecDegToScene(raDeg: number, decDeg: number): THREE.Vector3 {
  const raRad = raDeg * (Math.PI / 180)
  const decRad = decDeg * (Math.PI / 180)
  // 赤道坐标 → 与 eciToScene 同口径：scene = (cosδcosα, sinδ, −cosδsinα)
  const x = Math.cos(decRad) * Math.cos(raRad)
  const y = Math.sin(decRad)
  const z = -Math.cos(decRad) * Math.sin(raRad)
  return new THREE.Vector3(x, y, z).multiplyScalar(WESTERN_CONSTELLATION_RADIUS)
}

/** 星座中心方向：取该星座所有连线点的均值方向，归一后投到星空球面（用于放星座名标签） */
function constellationLabelPos(lines: [number, number][][]): THREE.Vector3 {
  const v = new THREE.Vector3()
  for (const ln of lines) for (const p of ln) v.add(raDecDegToScene(p[0], p[1]))
  if (v.lengthSq() === 0) return new THREE.Vector3()
  return v.normalize().multiplyScalar(WESTERN_CONSTELLATION_RADIUS)
}

/** 星座名标签数据（中文名 + 位置）：模板 v-for 与逐帧投影共用（模块级常量，位置固定不变） */
export const WESTERN_LABELS: { abbr: string; name: string; pos: THREE.Vector3 }[] =
  WESTERN_CONSTELLATIONS.map((c) => ({ abbr: c.abbr, name: c.name, pos: constellationLabelPos(c.lines) }))

export interface WesternConstellationsBuilt {
  /** 整个图层组（挂场景根） */
  group: THREE.Group
  /** 连线 Line2 材质：像素线宽依赖画布分辨率，resize 时须同步 resolution（见 BaseScene.onResize） */
  lineMaterial: LineMaterial
}

/**
 * 构建西方 88 星座连线图层（单几何单材质，顶点色统一淡青蓝）。
 * 返回的 group 需由调用方加入场景根；lineMaterial 需在拿到画布尺寸后设置 resolution。
 */
export function buildWesternConstellations(): WesternConstellationsBuilt {
  const group = new THREE.Group()
  group.frustumCulled = false

  const segPos: number[] = []
  const segCol: number[] = []
  const lc = new THREE.Color(WESTERN_COLOR)
  for (const c of WESTERN_CONSTELLATIONS) {
    for (const ln of c.lines) {
      for (let i = 0; i < ln.length - 1; i++) {
        const a = raDecDegToScene(ln[i][0], ln[i][1])
        const b = raDecDegToScene(ln[i + 1][0], ln[i + 1][1])
        segPos.push(a.x, a.y, a.z, b.x, b.y, b.z)
        // LineSegmentsGeometry.setColors 每个线段需给出两端颜色（与 setPositions 等长）
        segCol.push(lc.r, lc.g, lc.b, lc.r, lc.g, lc.b)
      }
    }
  }

  const lineGeo = new LineSegmentsGeometry()
  lineGeo.setPositions(segPos)
  lineGeo.setColors(segCol)
  const lineMaterial = new LineMaterial({
    linewidth: WESTERN_LINE_WIDTH,
    vertexColors: true,
    transparent: true,
    opacity: 0.42,
    blending: THREE.AdditiveBlending,
    depthWrite: false
  })
  const lines = new LineSegments2(lineGeo, lineMaterial)
  lines.frustumCulled = false
  lines.renderOrder = 1
  group.add(lines)

  return { group, lineMaterial }
}
