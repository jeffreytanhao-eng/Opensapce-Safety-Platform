/**
 * 西方 88 星座 —— IAU 划定的 88 个天区连线图层
 *
 * 现代天文学按国际天文学联合会（IAU）划定的 88 个星座（constellation）把全天空分割成
 * 互不重叠、有精确边界的天区，每颗天体（含深空天体）都唯一归属于某个星座，是天体定位的
 * 国际通用口径。本层与中国传统星官（三垣二十八宿，见 lunarMansions.ts）并列，展示 88 个
 * 星座的「连线」（把每个星座内主要亮星按传统连法连成折线），作为另一套认识天空的视角。
 *
 * ── 与中国星官层的区别 ────────────────────────────────────────
 * · 只画连线、不画星点（星官层画距星点，两套叠在一起时星点不会被连线淹没）；
 * · 88 个星座统一用一种淡青蓝色（WESTERN_COLOR），不按四象/三垣分色（那是中国星官的配色）；
 * · 同样默认隐藏（图例里单独一行开关），只在用户主动打开时出现，避免与星官层混淆。
 *
 * ── 数据来源与口径 ───────────────────────────────────────────
 * 连线数据取自 d3-celestial（Olaf Frohn）constellations.lines.json：
 *   github.com/ofrohn/d3-celestial/blob/master/data/constellations.lines.json
 * 原始坐标为 [赤经(度), 赤纬(度)]（J2000 赤道坐标，赤经可为负，等价于 +360°）；
 * 巨蛇座（Ser）在源数据中拆成「蛇首 / 蛇尾」两条 feature，按同一 ID 合并为一个星座。
 * 中文名按通行译名（88 座全表）。
 *
 * ── 坐标口径 ────────────────────────────────────────────────
 * 与项目 eciToScene 同源：赤道坐标 (x=cosδcosα, y=sinδ, z=−cosδsinα) → scene = (x, z, −y)，
 * 即 scene +Y = 天球北极。本图层挂在场景根（惯性系，不随地球自转），星座在天空中固定不动。
 */
